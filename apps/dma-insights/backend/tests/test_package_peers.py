def test_e2e_category_rollup_and_peer_fill() -> None:
    """Greenstone ships subcap-only scoring (no category_summary) + a peer
    table. parse_package should derive the 17 category rollups from subcaps
    AND fill peer median/p25/p75 from 06_peers — both previously empty."""
    from app.services.parsers.dma_package import parse_package

    root = (
        Path(__file__).resolve().parents[1]
        / "tests/fixtures/dma_packages_batches/batch_14/Greenstone - DMA"
    )
    if not root.exists():
        import pytest
        pytest.skip(f"fixture moved: {root}")
    pkg = parse_package(root)
    cats = pkg.category_scores
    assert len(cats) >= 15, "category rollup should be derived from subcaps"
    # every derived category has a sane mean score
    assert all(c.score is not None and 0 <= c.score <= 5 for c in cats)
    # peer distribution filled from the peer artifact
    assert sum(1 for c in cats if c.peer_median is not None) >= 15
    assert sum(1 for c in cats if c.peer_p25 is not None) >= 15
    p1c1 = next(c for c in cats if c.category_id == "P1C1")
    assert p1c1.peer_median == 2.75 and p1c1.peer_p25 == 2.5


def test_parse_peer_transposed_csv(tmp_path) -> None:
    from app.services.parsers.package_peers import parse_peer_transposed_csv
    p = tmp_path / "peer_comparison_table.csv"
    p.write_text(
        "Peer,Size_Tier,P1_Strategy,P2_Experience,P3_Ops\n"
        "TowneBank,Large,3.0,2.0,4.0\n"
        "PeerA,Large,2.0,3.0,3.0\n"
        "PeerB,Large,4.0,1.0,2.0\n"
    )
    out = parse_peer_transposed_csv(p)
    # pillar-keyed medians (median of 3.0/2.0/4.0 = 3.0 for P1)
    assert out["P1"].median == 3.0
    assert out["P2"].median == 2.0
    assert set(out) == {"P1", "P2", "P3"}
