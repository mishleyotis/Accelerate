def test_comparison_csv_tolerates_comments_and_drift(tmp_path: Path) -> None:
    p = tmp_path / "peer_comparison_table.csv"
    p.write_text(
        "# generated by bot v3\n"
        "# cohort: 3 peers\n"
        "Category,Acme,PeerA,PeerB,PeerC,peer_median,p25,p75,gap vs median,interpretation\n"
        "P1C1_digital_strategy,2.0,3.0,2.5,3.5,3.0,2.5,3.5,-1.0,BELOW MEDIAN\n"
        "P2C1_x,,,,,,,,,\n"  # no median → skipped
    )
    out = parse_peer_comparison_csv(p)
    assert set(out) == {"P1C1"}
    assert out["P1C1"].median == 3.0 and out["P1C1"].n == 3


