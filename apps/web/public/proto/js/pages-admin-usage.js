function uaRand(seed) {
  let a = seed >>> 0;
  return () => {
    a = a + 0x6D2B79F5 >>> 0;
    let t = a;
    t = Math.imul(t ^ t >>> 15, t | 1);
    t ^= t + Math.imul(t ^ t >>> 7, t | 61);
    return ((t ^ t >>> 14) >>> 0) / 4294967296;
  };
}
function uaPick(rnd, arr, wfn) {
  const tot = arr.reduce((s, x) => s + wfn(x), 0);
  let r = rnd() * tot;
  for (const x of arr) {
    r -= wfn(x);
    if (r <= 0) return x;
  }
  return arr[arr.length - 1];
}
function uaSession(rnd, u, start, ents, sid) {
  const allowed = Object.values(UA_PAGES).filter(p => !p.roles || p.roles.includes(u.role));
  const n = 3 + Math.floor(rnd() * 9);
  let client = ents[Math.floor(rnd() * ents.length)];
  const pages = [],
    features = [];
  let t = start.getTime();
  for (let i = 0; i < n; i++) {
    const pg = i === 0 && rnd() < 0.7 ? UA_PAGES.dashboard : uaPick(rnd, allowed, p => p.w * (u.role === "AE" && (p.key === "platform" || p.key === "overview") ? 1.5 : 1) * (u.role === "ANALYST" && (p.key === "heatmap" || p.key === "health") ? 1.6 : 1));
    if (pg.client && rnd() < 0.18) client = ents[Math.floor(rnd() * ents.length)];
    const secs = Math.round(pg.dwell[0] + rnd() * (pg.dwell[1] - pg.dwell[0]));
    pages.push({
      key: pg.key,
      label: pg.label,
      client: pg.client ? client.id : null,
      clientName: pg.client ? client.name : null,
      at: new Date(t),
      secs,
      view: true
    });
    if ((pg.key === "overview" || pg.key === "platform") && rnd() < 0.3) features.push("intelligence");
    if ((pg.key === "overview" || pg.key === "heatmap" || pg.key === "insights") && rnd() < 0.4) features.push("evidence");
    if (pg.key === "platform" && u.role === "AE" && rnd() < 0.28) features.push("ae_note");
    if (pg.key === "overview" && u.role === "AE" && rnd() < 0.18) features.push("meeting_prep");
    if (rnd() < 0.05) features.push("export");
    t += secs * 1000;
  }
  return {
    id: "S-" + sid,
    email: u.email,
    role: u.role,
    start,
    end: new Date(t),
    secs: Math.round((t - start.getTime()) / 1000),
    pages,
    features: features.map(f => ({
      f,
      at: start
    })),
    device: rnd() < 0.86 ? "Desktop · Chrome" : rnd() < 0.5 ? "Desktop · Safari" : "iPad · Safari"
  };
}
