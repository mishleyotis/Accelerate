function uaNameOf(email) {
  if (typeof window !== "undefined" && typeof window.displayNameOf === "function") return window.displayNameOf(email);
  const parts = String(email || "").split("@")[0].split(/[._-]+/).filter(Boolean);
  if (parts.length === 1 && parts[0].length <= 3) return parts[0].toUpperCase();
  return parts.map(w => w[0].toUpperCase() + w.slice(1)).join(" ") || email;
}
