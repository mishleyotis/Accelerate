"""Page endpoints — the serving tier's read path (stage 5, TRD §08).

One resolution, then one select per section. Not a wide join: a section
that failed to promote returns no row, which is a different fact from a
section that promoted empty, and a join would flatten the two into the
same nulls. Nothing here recomputes a score, delta, share or age — every
one of those is either promoted or generated by the database.
"""
from __future__ import annotations

