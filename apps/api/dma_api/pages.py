AUDIENCES = ("internal", "customer")


def _iso(v):
    """A timestamp as ISO-8601, or whatever it already was. One helper, so
    the envelope cannot format one instant two ways."""
    return v.isoformat() if hasattr(v, "isoformat") else v


class ApiError(Exception):
    def __init__(self, status: int, code: str, detail: str):
        super().__init__(detail)
        self.status, self.code, self.detail = status, code, detail


def _rows(cur, table: str, run_id) -> list[dict]:
    """Every item-grain section's rows, IN THE ORDER THE PRODUCER SENT THEM.

    `ORDER BY id` is load-bearing, not tidiness. Rule 10 is "order is
    meaning" — findings are ranked, phases sequenced, events chronological —
    and promote inserts each section's items in payload order, so the
    BIGSERIAL id IS that order. Without the clause PostgreSQL returns heap
    order, which is not insertion order, is not stable across reads, and
    changes after any UPDATE or VACUUM on the serving table.

    Measured on the reference client: `overview.firmographics.fields` served
    its first seven rows left-rotated by two — 13 in, 13 out, identical
    multiset, 7 of 13 positions carrying a different row — putting
    return-on-assets where branch count was on a ranked identity card. The
    other arrays happened to come back in insertion order on that read and
    nothing in the query made that hold on the next one. 23 of the 34
    writers are item-grain.
    """
    order = " ORDER BY id" if _has_id(cur, table) else ""
    cur.execute(f"SELECT * FROM {table} WHERE run_id = %s{order}", (run_id,))
    cols = [d[0] for d in cur.description]
    return [dict(zip(cols, r)) for r in cur.fetchall()]


_HAS_ID: dict = {}


def _has_id(cur, table: str) -> bool:
    """Whether this serving table carries the BIGSERIAL, asked once per table.

    Measured: the 23 ITEM-grain tables all have `id`; the 10 RUN-grain ones
    (overview_scores, platform_story, insights_landscape, …) do not, because
    one row per run needs no ordering. A blanket `ORDER BY id` therefore 500s
    exactly the pages carrying a run-grain section — which is what it did in
    production for the four minutes between that deploy and this fix, on
    overview and platform, while every fake-cursor test stayed green because
    a fake cursor answers whatever it is asked.

    Asked BEFORE the select, never after: a failed statement aborts the whole
    transaction in PostgreSQL and every later query on the request then fails
    with 25P02, so "try it and fall back" would take the page down anyway.
    """
    if table not in _HAS_ID:
        cur.execute("""SELECT 1 FROM information_schema.columns
                        WHERE table_schema = 'public' AND table_name = %s
                          AND column_name = 'id'""", (table,))
        _HAS_ID[table] = cur.fetchone() is not None
    return _HAS_ID[table]


def resolve_run(cur, display_id: str, run: str | None, allow_history: bool):
    """The entity and the run to serve, read from the ONE materialised view
    svc_api is granted (0013). Not the base tables: svc_api holds no SELECT
    on entities or runs by design, and resolving the active run in two
    places is how a header and its rows come to disagree."""
    cur.execute("""SELECT entity_id, display_id, legal_name, sub_vertical, size_tier,
                          run_id, request_id, run_seq, is_active, run_status,
                          composite, scored_cells, catalogue_cells,
                          ccg_catalog_version, completed_at, promoted_at,
                          assessment_date, assessment_date_basis,
                          assessment_date_source, refresh_due_date,
                          entity_domain, trading_name,
                          supplementary_sub_verticals
                     FROM serving_directory
                    WHERE display_id = %s
                    -- NULLS LAST is load-bearing: `is_active` is a nullable
                    -- boolean, and PostgreSQL sorts NULL FIRST under DESC. A
                    -- promoted run that never had the column set would
                    -- therefore sort AHEAD of the active one, and this
                    -- function would 404 an entity that is serving.
                    ORDER BY is_active DESC NULLS LAST, promoted_at DESC""",
                (display_id,))
    rows = cur.fetchall()
    if not rows:
        # No promoted run for this entity — including an entity that exists
        # but has never promoted, which is the same fact to a reader.
        raise ApiError(404, "entity_not_found",
                       f"no promoted run for {display_id!r}")
    if run:
        picked = next((r for r in rows if str(r[5]) == str(run)), None)
        if picked is None:
            raise ApiError(404, "entity_not_found",
                           f"run {run} has no promoted rows under {display_id}")
        if not picked[8] and not allow_history:
            raise ApiError(409, "run_superseded",
                           "the pinned run is no longer active; pass "
                           "history=true to read it deliberately")
    else:
        picked = rows[0]
        if not picked[8]:
            raise ApiError(404, "entity_not_found",
                           f"{display_id} has no active promoted run")

    # `trading_name` travels so a reader whose `entity_name` is NULL still
    # gets a name (the web's legal -> trading -> display id fallback), and
    # the supplementary codes so every scope call below admits the variant
    # cells of each sub-vertical the entity is bound to (0061). The display
    # label stays the PRIMARY's alone.
    entity = {"display_id": picked[1], "entity_name": picked[2],
              "trading_name": picked[21],
              "sub_vertical": picked[3], "size_tier": picked[4],
              "supplementary_sub_verticals": list(
                  resolve_supplementary(picked[22],
                                        resolve_subvertical(picked[3])))}
    run_meta = {"run_id": str(picked[5]), "request_id": picked[6],
                "run_seq": picked[7],
                "completed_at": picked[14].isoformat() if picked[14] else None,
                "promoted_at": picked[15].isoformat() if picked[15] else None,
                "ccg_catalog_version": picked[13], "scored_cells": picked[11],
                "catalogue_cells": picked[12], "status": picked[9],
                "is_active": bool(picked[8]),
                "composite": float(picked[10]) if picked[10] is not None else None,
                # The assessment date and the rung it came from travel with
                # every run this function resolves, so a page header cannot
                # render a date whose provenance the cadence block contradicts
                # (0031). `completed_at` above is retained: it is what the
                # ingest wrote, and the two agreeing is a fact worth being
                # able to check rather than one to assume.
                "assessment_date": (picked[16].isoformat()
                                    if hasattr(picked[16], "isoformat")
                                    else picked[16]),
                "assessment_date_basis": picked[17],
                "assessment_date_source": picked[18],
                "refresh_due_date": (picked[19].isoformat()
                                     if hasattr(picked[19], "isoformat")
                                     else picked[19]),
                # The entity's OWN publication domain (0045). Carried on the
                # view because svc_api holds no grant on `entities`, and read
                # here rather than queried in `computed` so the read path
                # keeps resolving the run in exactly one place.
                "entity_domain": picked[20]}
    return picked[0], entity, run_meta, picked[15]


