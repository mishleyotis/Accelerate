SERVE_RULES = "serve-rules@12"


#: Keys whose value is a list of cited evidence ids (chips), and the one
#: whose value is a single cited id (a row).
_CITATION_LISTS = ("e_ids", "supporting_e_ids", "evidence_ids")


def cited_ids(data) -> set:
    """Every evidence id a section body cites, at any depth."""
    out: set = set()

    def walk(node):
        if isinstance(node, dict):
            for k, v in node.items():
                if k in _CITATION_LISTS and isinstance(v, list):
                    out.update(e for e in v if isinstance(e, str) and e)
                elif k == "e_id" and isinstance(v, str) and v:
                    out.add(v)
                else:
                    walk(v)
        elif isinstance(node, list):
            for v in node:
                walk(v)

    walk(data)
    return out


def evidence_scope(cur, entity_id, ids, *, promoted_at) -> dict:
    """Which of `ids` are INTERNAL SPANS (never served to a customer) and
    which are shareable SPLIT SPANS (served under their customer
    attribution). One entity-scoped query; ids are resolved through
    `resolve_evidence_id` exactly as the drawer resolves them (0046), so a
    superseded citation is judged by the row a reader would open.

    RC-08 / D-10: the producer's `internal_only` marking was the only thing
    between an internal-origin row and a customer chip, and on SWBC the
    whole-row marking of 20 shareable discovery rows emptied 24 drawers. The
    serve layer now decides from the stored origin and the 0063 split, and
    the marking is no longer load-bearing for either direction.

    `promoted_at` is the served run's, and it is REQUIRED: a span serves
    under its attribution only on a run promoted at or after the span was
    minted (evidence.attribution_bound). On a run promoted before, the span
    is withheld like any internal row, so a span minted for a later run
    changes nothing on the live one until a payload citing it is promoted
    (RC-08 review, 2026-10-04).
    """
    from .evidence import attribution_bound
    scope = {"withheld": set(), "attribution": {}}
    wanted = sorted(i for i in (ids or ()) if isinstance(i, str) and i)
    if not wanted:
        return scope
    cur.execute(
        """SELECT w.cited, ei.origin::text, ei.customer_attribution,
                  ei.customer_attribution_at
             FROM unnest(%s::text[]) AS w(cited)
             JOIN evidence_index ei
               ON ei.e_id = resolve_evidence_id(w.cited)
            WHERE ei.entity_id = %s""", (wanted, entity_id))
    for cited, origin, attribution, attributed_at in cur.fetchall():
        if (origin or "").lower() != "internal":
            continue
        if (isinstance(attribution, str) and attribution.strip()
                and attribution_bound(attributed_at, promoted_at)):
            scope["attribution"][cited] = attribution.strip()
        else:
            scope["withheld"].add(cited)
    return scope


def etag_for(run_meta: dict, audience: str) -> str:
    """W/"<run_id>.<promoted_at epoch>.<audience>.<serve-rules>" — the
    audience is part of the tag because one run serves two different
    documents (TRD §19), and the serving-rule tag is part of it because the
    same run also serves different documents before and after a rule
    change."""
    promoted = run_meta.get("promoted_at") or ""
    epoch = "0"
    if promoted:
        from datetime import datetime
        try:
            epoch = str(int(datetime.fromisoformat(promoted).timestamp()))
        except ValueError:
            epoch = "0"
    return f'W/"{run_meta["run_id"]}.{epoch}.{audience}.{SERVE_RULES}"'


def withheld_entry(report: dict) -> dict | None:
    """What a withheld section leaves behind in the page body.

    Two different absences. A section on the NEVER_SERVED allowlist was
    excluded by owner adjudication for EVERY audience — its key must not
    appear in the payload at all (owner, 2026-08-20: "do not include any
    surface I excluded in the live payload"). A stub with data:null still
    names the surface, which is inclusion. An audience withholding, by
    contrast, keeps the stub: the internal reader of a customer preview is
    owed the fact that a surface exists and was withheld, not a silent hole.
    """
    if report.get("never_served"):
        return None
    return {
        "data": None, "data_source": "withheld", "provenance": None,
        "produced_at": None, "producer_version": None, "e_ids": [],
        "empty_state": {"kind": "withheld_for_audience",
                        "reason": "this surface is not served to the "
                                  "customer audience",
                        "sources_searched": []},
    }


# `audience` has NO default. It used to default to "internal", which is
# fail-OPEN: unreachable over HTTP because all twelve routes pass a value
# normalised by `normalise_audience`, but a new in-process caller that
# omitted the kwarg would have been handed the full internal body in
# silence. The module that decides redaction defaults to `customer` for
# exactly this reason (redaction.normalise_audience); the function it
# decides for should not disagree with it.
def build_page(cur, page: str, display_id: str, audience: str,
               run: str | None = None, role: str | None = None,
               allow_history: bool = False) -> dict:
    if audience not in AUDIENCES:
        raise ApiError(400, "unknown_audience",
                       f"audience must be one of {' · '.join(AUDIENCES)}")
    sections = page_sections(page)
    if not sections:
        raise ApiError(404, "unknown_page", f"no page {page!r}")
    forbidden = page_forbidden(page, audience, role)
    if forbidden:
        raise ApiError(403, "audience_forbidden", forbidden)

    entity_id, entity, run_meta, _ = resolve_run(cur, display_id, run, allow_history)

    out_sections = {}
    for section in sections:
        r = readers()[(page, section)]
        if r["grain"] == "none":
            # The evidence store is not a per-run serving table: promote
            # writes no rows for it (its writer grain is "none") and it is
            # keyed by evidence id, not run. Saying so is honest; querying
            # it by run_id would be a column that does not exist. The
            # store is read through the evidence drawer, per id.
            out_sections[section] = {
                "data": None, "data_source": "external",
                "provenance": None, "produced_at": None,
                "producer_version": None, "e_ids": [],
                "empty_state": {
                    "kind": "served_from_evidence_store",
                    "reason": ("this section's rows live in the run's evidence "
                               "store and are read by evidence id rather than "
                               "by page"),
                    "sources_searched": []},
            }
            continue
        rows = _rows(cur, r["table"], run_meta["run_id"])
        built = assemble(page, section, rows)
        if page == "heatmap" and section == "value_chain":
            # H9 is SERVER-DERIVED: its contract is `fields: {}` and the
            # Backend Schema derives it by joining ccg_value_chains to
            # ccg_vc_mapping against the run's served cells. The promoted
            # row contributes only its envelope (the normal promote writes
            # envelope-only for this section); the arrangement is computed
            # here whether or not that row exists, and the empty state
            # names what was searched when the catalogue has none.
            out_sections[section] = serve_value_chain(
                cur, entity, run_meta, built, audience)
            continue
        if built is None:
            # A section with no serving row did not promote. Reported as an
            # explicit state rather than an empty object: blank and broken
            # must not look the same (TRD §08).
            out_sections[section] = {
                "data": None, "data_source": "empty", "provenance": None,
                "produced_at": None, "producer_version": None, "e_ids": [],
                "empty_state": {"kind": "section_not_promoted",
                                "reason": "no serving row for this run",
                                "sources_searched": []},
            }
            continue

        env, stamps = built["env"], built["stamps"]
        # Computed-at-read BEFORE redaction, so a census count is subject to
        # the same audience rules as a promoted one — and so a field the
        # contract calls computed is never served as the producer's copy of
        # a number the app was supposed to derive (invariant 8).
        computed_apply(cur, page, section, built["data"], run_meta, entity_id)
        # T2 SUB-VERTICAL SCOPE, on the way out.
        #
        # ET-05 already refuses a foreign variant cell at SUBMIT, so a payload
        # promoted under a resolvable sub-vertical cannot carry one. This is
        # for the payloads promoted when it was NOT resolvable: until
        # 2026-08-15 `resolve_subvertical` matched only the whole normalised
        # string, so 44 of the 93 corpus manifests carrying a sub-vertical
        # would have ingested with no scope at all — and an unresolved entity
        # keeps every cell, deliberately and silently. Widening the resolver
        # turns those entities from unscoped into scoped, which retroactively
        # makes their PROMOTED payloads wrong; the gate cannot reach back, and
        # this can.
        #
        # Same one-sided rule as everywhere else: base cells, family and
        # product variants, and an unresolved entity all keep everything.
        scope_sections(entity.get("sub_vertical"), built["data"],
                       entity.get("supplementary_sub_verticals"))
        scope = None
        if audience == "customer":
            ids = cited_ids(built["data"])
            scope = (evidence_scope(cur, entity_id, ids,
                                    promoted_at=run_meta.get("promoted_at"))
                     if ids else None)
        data, report = redact_section(page, section, built["data"],
                                      env.get("internal_only"), audience,
                                      evidence_scope=scope)
        if data is None:
            entry = withheld_entry(report)
            if entry is None:
                continue
            out_sections[section] = entry
            continue

        # THROUGH THE WALKER, not around it. This read the envelope and
        # attached the result raw, which is the whole of MEM-0137: every rule
        # in `redaction` applied to the section's content and to nothing in
        # its empty state. Measured live on three promoted clients — a
        # customer body carrying `get_evidence('platform')`, `r_layer` and
        # the literal `CUSTOMER_WITHHELD` inside
        # `platform.starters.empty_state.sources_searched`.
        empty, empty_dropped = redact_empty_state(
            env.get("empty_state"), audience)
        out_sections[section] = {
            "data": data,
            "data_source": "empty" if empty else "producer",
            "provenance": stamps.get("provenance"),
            # The instant this SECTION was produced, which is what the
            # contract's envelope says this field is, and not the instant the
            # run was promoted.
            #
            # This served `promoted_at` on 34 of 34 sections across all six
            # pages of the reference client — 0 of 34 preserved — while the
            # producer's own value sat in `env`, loaded by `assemble` from a
            # column `writer_spec` fills from `env:produced_at`, and was
            # discarded here. A page whose sections were synthesised 25 hours
            # apart by two different producers reported all of them at one
            # instant, so a reader could not tell which section was stale.
            # `promoted_at` is not lost: it is the run's, it is on the run
            # envelope, and it is in the ETag.
            "produced_at": _iso(env.get("produced_at")
                                or stamps.get("promoted_at")),
            "producer_version": stamps.get("producer_version"),
            "e_ids": env.get("e_ids") or [],
            "empty_state": empty,
        }
        removed = (len(report["paths_stripped"]) + len(report["keys_stripped"])
                   + len(report["vendor_named"]) + len(empty_dropped)
                   # Rows a customer rule held back (D4, internal spans,
                   # gate rows about withheld sections) are removals too.
                   + report.get("d4_rows_withheld", 0)
                   + report.get("evidence_scope_withheld", 0)
                   + len(report.get("gates_withheld_target") or ()))
        if audience == "customer" and removed:
            # A COUNT, not the paths. The receipt exists so a reader can tell
            # blank-because-withheld from blank-because-empty, and for that
            # the number is enough. The path strings are not: they carry the
            # field names, and `platform_story.platforms[0].zennify_pathway`
            # names the assessing vendor five times in a client's own body —
            # the leak this redaction pass exists to close, re-opened by its
            # own receipt. Measured in production after the first fix: the
            # only five occurrences left were in this list.
            out_sections[section]["redacted_count"] = removed
            out_sections[section]["redaction_note"] = (
                "fields on this surface are held for the internal audience")

    return {"entity": entity, "run": run_meta, "audience": audience,
            "page": page, "sections": out_sections}
