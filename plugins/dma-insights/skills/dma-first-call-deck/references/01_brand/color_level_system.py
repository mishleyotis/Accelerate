def expand_slide14_blocks():
    """Expand SLIDE_14_BLOCK_OFFSETS × BLOCKS_158 into a full shape-index dict.

    Returns a dict mapping python-pptx shape_idx → role tuple for all 136
    block shapes (17 blocks × 8 offsets). The caller merges this with
    SLIDE_14_SHARED_ROLES to get the complete Slide 14 role catalogue.
    """
    block_roles = {}
    for block_num, base in enumerate(BLOCKS_158):
        cap_name = CAPABILITY_ORDER[block_num]
        for offset, (role_name, ctype, source, palette_key, wf, wb, wt, wtc) in SLIDE_14_BLOCK_OFFSETS.items():
            shape_idx = base + offset
            # Specialize role name per capability (e.g., "bg_card_cap01")
            specialized_role = f"{role_name}_cap{block_num+1:02d}"
            # Specialize source to point at the specific capability
            if ctype == "data":
                specialized_source = f"s14.scores[{block_num}]"  # cap index
            elif ctype == "text" and "cap.score" in source:
                specialized_source = f"s14.scores[{block_num}] formatted"
            elif ctype == "text" and "cap.name" in source:
                specialized_source = f"CAPABILITY_ORDER[{block_num}] = {cap_name!r}"
            else:
                specialized_source = source
            block_roles[shape_idx] = (specialized_role, ctype, specialized_source, palette_key, wf, wb, wt, wtc)
    return block_roles


def get_slide14_full_roles():
    """Return Slide 14 complete role catalogue: shared + expanded per-block."""
    return {**SLIDE_14_SHARED_ROLES, **expand_slide14_blocks()}


