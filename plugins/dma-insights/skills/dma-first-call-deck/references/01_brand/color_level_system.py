# 8. EXPECTED-HEX RESOLVER (used by both editors and QA)
# ══════════════════════════════════════════════════════════════════════════════

def resolve_data_source(source_path: str, input_data: dict):
    """Walk a dotted path like 's10.rec_scores[2]' against input_data."""
    import re
    # Strip leading namespace ('s10.', 's13.', 's14.', 'input.', 'cap.', 'sv.')
    # For now, support the literal paths used in role catalogues
    parts = re.split(r'\.|\[|\]', source_path)
    parts = [p for p in parts if p]  # drop empties from split

    cur = input_data
    for p in parts:
        if p.isdigit():
            cur = cur[int(p)]
        else:
            if isinstance(cur, dict):
                if p in cur:
                    cur = cur[p]
                else:
                    raise KeyError(f"Key {p!r} not found in input (path: {source_path!r})")
            else:
                # Attribute-style access — we don't support this yet; paths use dict access
                raise TypeError(f"Cannot descend into {type(cur).__name__} with key {p!r}")
    return cur


def get_expected_hex(role_spec, input_data, slide_num=None):
    """Given a role tuple, input data, and (for data roles) the slide number,
    return the expected hex string.

    Returns None for text/image roles (no color to verify).
    For "data" roles: derives hex via score_to_level_* → LEVEL_*TIER[level][palette_key]
    For "static" roles: looks up STATIC_COLORS[source]
    For "theme_ref" roles: returns "scheme:" + the schemeClr val (caller checks XML)

    slide_num discriminates 4-tier vs 5-tier palettes since `label_text` is a key
    in both. Slide 13 → 5-tier; Slides 10, 14 → 4-tier.
    """
    role_name, ctype, source, palette_key, wf, wb, wt, wtc = role_spec

    if ctype == "text" or ctype == "image":
        return None

    if ctype == "static":
        if source not in STATIC_COLORS:
            raise KeyError(f"STATIC_COLORS has no key {source!r} (role {role_name})")
        return STATIC_COLORS[source]

    if ctype == "theme_ref":
        if source not in THEME_REFS:
            raise KeyError(f"THEME_REFS has no key {source!r} (role {role_name})")
        val = THEME_REFS[source]
        return f"scheme:{val}" if val is not None else None

    if ctype == "data":
        if input_data is None:
            return None  # caller doesn't have the inputs; can't resolve
        if slide_num is None:
            raise ValueError(
                f"get_expected_hex requires slide_num for data role {role_name!r} "
                f"to disambiguate 4-tier vs 5-tier palette"
            )
        score = resolve_data_source(source, input_data)
        if slide_num == 13:
            level = score_to_level_5tier(score)
            if palette_key not in LEVEL_5TIER[level]:
                raise KeyError(f"LEVEL_5TIER[{level!r}] has no key {palette_key!r}")
            return LEVEL_5TIER[level][palette_key]
        elif slide_num in (10, 14):
            level = score_to_level_4tier(score)
            if palette_key not in LEVEL_4TIER[level]:
                raise KeyError(f"LEVEL_4TIER[{level!r}] has no key {palette_key!r}")
            return LEVEL_4TIER[level][palette_key]
        else:
            raise ValueError(
                f"No palette assigned for data role on slide {slide_num!r} "
                f"(role {role_name!r})"
            )

    raise ValueError(f"Unknown content_type {ctype!r} in role {role_name!r}")


